"""
q6_math_module_demo.py

Q6: Uses the math module to calculate square root, power, factorial,
ceiling, and floor. Only the specific names needed are imported.
"""

from math import sqrt, pow, factorial, ceil, floor

print("Q6: Built-in math module")
print("Square root of 81:", sqrt(81))
print("2 to the power of 10:", pow(2, 10))
print("Factorial of 6:", factorial(6))
print("Ceiling of 4.2:", ceil(4.2))
print("Floor of 4.8:", floor(4.8))
